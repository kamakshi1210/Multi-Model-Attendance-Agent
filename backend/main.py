@app.get("/api/insights/student/{student_id}")
async def get_student_insight(student_id: str):
    """
    Generates personalized reflection report for an anonymous participant (Epic 5).
    """
    target_data = None
    target_pid = student_id
    for pid, data in session_manager.person_history.items():
        anon = session_manager.get_anonymous_id(pid)
        if anon == student_id or str(pid) == student_id:
            target_data = data
            target_pid = anon
            break
            
    if not target_data:
        # Check database if session is stopped
        db = SessionLocal()
        try:
            sp = db.query(SessionPerson).filter(SessionPerson.person_id == student_id).order_by(SessionPerson.id.desc()).first()
            if sp:
                summary = {
                    "id": student_id,
                    "attendance_status": sp.attendance_status or "Present",
                    "presence_percentage": sp.presence_percentage or 100.0,
                    "avg_attention": sp.avg_attention or 75.0,
                    "active_duration": sp.total_time_present or 0.0
                }
                reflection = gemini_agent.generate_student_reflection(summary)
                return {
                    "student_id": student_id,
                    "reflection": reflection.model_dump() if hasattr(reflection, "model_dump") else reflection.dict()
                }
        finally:
            db.close()
        return {"reflection": "Participant not found."}
        
    start_time = session_manager.active_session_data.get('start_time') if session_manager.active_session_data else datetime.utcnow()
    total_elapsed = max(1.0, (datetime.utcnow() - start_time).total_seconds())
    presence_pct = round(min(100.0, (target_data.get('active_seconds', 0.0) / total_elapsed) * 100.0), 1)
    
    if presence_pct >= ATTENDANCE_PRESENT_THRESHOLD:
        att_status = "Present"
    elif presence_pct >= ATTENDANCE_PARTIAL_THRESHOLD:
        att_status = "Partial"
    else:
        att_status = "Absent"
        
    att_list = target_data.get('attention', [])
    avg_att = round(float(np.mean(att_list)), 1) if att_list else 0.0
    
    summary = {
        "id": target_pid,
        "attendance_status": att_status,
        "presence_percentage": presence_pct,
        "avg_attention": avg_att,
        "active_duration": target_data.get('active_seconds', 0.0)
    }
    
    reflection = gemini_agent.generate_student_reflection(summary)
    return {
        "student_id": target_pid,
        "reflection": reflection.model_dump() if hasattr(reflection, "model_dump") else reflection.dict()
    }

