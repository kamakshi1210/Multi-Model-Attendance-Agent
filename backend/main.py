# AI Insights & Suggestions Endpoints (Epic 4 & 5)
@app.get("/api/suggestions/current")
async def get_ai_suggestions():
    """
    Returns prioritized teaching recommendations generated by Gemini or grounded fallback,
    formatted specifically for the frontend SuggestionBox component.
    """
    if not session_manager.active_session_id:
        return []
    
    audio_summary = audio_analyzer.get_session_summary()
    person_history = session_manager.person_history
    session_summary = fusion_engine.get_session_summary_for_gemini(
        session_id=str(session_manager.active_session_id),
        person_history=person_history,
        audio_summary=audio_summary
    )
    
    insights = gemini_agent.generate_classroom_insights(session_summary)
    
    suggestions = []
    priorities = ["High", "Med", "Low"]
    impacts = ["Engagement Boost", "Focus Recovery", "Pacing Alignment"]
    for i, s in enumerate(insights.teaching_suggestions):
        suggestions.append({
            "priority": priorities[i % len(priorities)],
            "action": s,
            "impact": impacts[i % len(impacts)]
        })
    return suggestions

