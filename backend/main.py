@app.websocket("/ws/video")
async def video_endpoint(websocket: WebSocket):
    await websocket.accept()
    try:
        camera.start()
    except Exception as e:
        print(f"Camera start notice: {e}")

    latest_client_frame = None

    async def receive_frames():
        nonlocal latest_client_frame
        while True:
            try:
                data = await websocket.receive_bytes()
                if data:
                    nparr = np.frombuffer(data, np.uint8)
                    decoded = cv2.imdecode(nparr, cv2.IMREAD_COLOR)
                    if decoded is not None:
                        latest_client_frame = decoded
            except Exception:
                break

    recv_task = asyncio.create_task(receive_frames())

    try:
        while True:
            # Use client webcam frame if available, else camera.get_frame() (physical or simulation)
            if latest_client_frame is not None:
                frame = latest_client_frame
                latest_client_frame = None
            else:
                frame = camera.get_frame()

            processed_frame, metrics = session_manager.process_frame(frame)
            
            # Fuse with live audio signals
            current_audio = audio_analyzer.get_session_summary()
            fused = fusion_engine.fuse_signals(metrics, current_audio)
            
            metrics['engagement_score'] = fused['engagement_score']
            metrics['engagement_state'] = fused['engagement_state']
            metrics['fusion'] = fused
            
            # Generate Real-time alerts
            recs = recommendations_engine.generate_realtime_recommendations(metrics)
            metrics['recommendations'] = recs
            
            _, buffer = cv2.imencode('.jpg', processed_frame)
            await websocket.send_bytes(buffer.tobytes())
            await websocket.send_text(json.dumps(metrics))
            await asyncio.sleep(0.08) # ~12 FPS
            
    except WebSocketDisconnect:
        print("Video Client disconnected")
    except Exception as e:
        print(f"Video Error: {e}")
    finally:
        recv_task.cancel()

@app.websocket("/ws/audio")
async def audio_endpoint(websocket: WebSocket):
    await websocket.accept()
    db = SessionLocal()
    last_db_log = 0
    try:
        while True:
            data = await websocket.receive_bytes()
            audio_array = np.frombuffer(data, dtype=np.float32)
            metrics = audio_analyzer.analyze_audio_chunk(audio_array)
            if metrics:
                await websocket.send_json(metrics)
                if session_manager.active_session_id and (time.time() - last_db_log > 3.0):
                    db_metric = AudioMetric(
                        session_id=str(session_manager.active_session_id),
                        noise_db=metrics['noise_db'],
                        speech_ratio=metrics['speech_ratio'], 
                        activity_type=metrics['activity_type']
                    )
                    db.add(db_metric)
                    db.commit()
                    last_db_log = time.time()
    except WebSocketDisconnect:
        pass
    except Exception as e:
        print(f"Audio notice: {e}")
    finally:
        db.close()

